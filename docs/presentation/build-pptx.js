const pres = new pptxgen();
pres.layout = "LAYOUT_16x9"; // 10 x 5.625 in, same ratio as the 1920x1080 designs
pres.author = "lDo2x";
pres.company = "2X Ping";
pres.title = "2X Ping - دليل البرنامج";
pres.rtlMode = true;
pres.defineSlideMaster({ title: "FULL_IMAGE", background: { color: "140F1E" } });

pres.addSection({ title: "2X Ping" });
notes.forEach((text, i) => {
  const slide = pres.addSlide({ masterName: "FULL_IMAGE", sectionTitle: "2X Ping" });
  slide.addImage({
    path: path.join(IMG, "slide" + (i + 1) + ".png"),
    x: 0, y: 0, w: 10, h: 5.625,
    altText: "Slide " + (i + 1),
    objectName: "Slide image " + (i + 1),
  });
  slide.addNotes(text);
});

pres.writeFile({ fileName: OUT }).then(f => console.log("written " + f));
